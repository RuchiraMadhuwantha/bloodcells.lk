export const BANK_REPORT_TYPES = [
  ['inventory', 'Blood Inventory Report'], ['donations', 'Recorded Donation Report'],
  ['requests', 'Hospital Blood Request Report'], ['expiry', 'Blood Expiry Report'],
  ['campaigns', 'Campaign Donation Report'], ['transfers', 'Blood Transfer Report'],
];
export const buildBankReport = (resource, filters, generatedBy) => {
  if (!resource?.available || !resource.complete) throw new Error('A complete authorized source is required.');
  if (!['inventory', 'donations', 'requests'].includes(filters.type)) throw new Error('This report source is not available.');
  if (filters.start && filters.end && filters.start > filters.end) throw new Error('Start date must be on or before end date.');
  let items = resource.items;
  if (filters.type === 'donations') items = items.filter((r) => r.status === 'completed');
  items = items.filter((r) => {
    const date = filters.type === 'donations' ? r.appointmentDate : r.createdAt;
    return (!filters.group || r.bloodGroup === filters.group) && (filters.type === 'inventory' ||
      ((!filters.district || r.district === filters.district) && (!filters.location || r.hospitalName === filters.location) &&
       (!filters.start || date >= filters.start) && (!filters.end || (date && date <= filters.end))));
  });
  const stock = filters.type === 'inventory';
  const donations = filters.type === 'donations';
  const columns = stock ? ['Blood group', 'Recorded units', 'Location', 'Stock status', 'Last stock update'] :
    donations ? ['Completed appointment reference', 'Donation date', 'Blood group', 'Collected units', 'Collected volume (mL)', 'Donation location', 'District'] :
    ['Request ID', 'Hospital', 'Submission date', 'Blood group', 'Requested units', 'Urgency', 'Status'];
  const rows = items.map((r) => stock ? [r.bloodGroup, r.availableUnits, 'Not recorded for combined stock', r.level, r.lastRestockedAt || 'Not recorded'] :
    donations ? [r.reference, r.appointmentDate, r.bloodGroup, r.collectedUnits ?? 'Not recorded', r.collectedVolumeMl ?? 'Not recorded', r.hospitalName, r.district] :
    [r.reference, r.hospitalName, r.createdAt, r.bloodGroup, r.quantity, r.urgencyLabel || r.urgency, r.statusLabel || r.status]);
  return {
    title: BANK_REPORT_TYPES.find(([type]) => type === filters.type)[1], hospital: 'Blood Bank network', hospitalCode: generatedBy,
    scopeLabel: 'Scope', codeLabel: 'Generated by', generatedAt: new Date().toISOString(),
    period: stock ? 'Current stock; past stock totals are not available' : (filters.start || 'First recorded date') + ' to ' + (filters.end || 'Latest recorded date'),
    group: filters.group || 'All groups', status: donations ? 'Completed appointments' : 'All recorded statuses',
    columns, rows,
    summary: stock ? { 'Blood groups': rows.length, 'Recorded units': items.reduce((s, r) => s + Number(r.availableUnits), 0) } :
      donations ? { 'Completed donations': rows.length, 'Collected units': items.reduce((n,r) => n + (r.collectedUnits || 0), 0), 'Collected volume (mL)': items.reduce((n,r) => n + (r.collectedVolumeMl || 0), 0) } :
      { Requests: rows.length, 'Requested units': items.reduce((s, r) => s + Number(r.quantity), 0), Pending: items.filter((r) => r.status === 'pending').length, Fulfilled: items.filter((r) => r.status === 'fulfilled').length },
    sourceNote: stock ? 'Current combined stock totals. Expiry dates, locations and past stock totals are not available. Staff must check whether blood can be used.' :
      donations ? 'Source: completed appointment records. Totals include only hospital-recorded quantities; historical unknown quantities remain unrecorded.' :
      'Source: complete authorized blood bank hospital-request list, filtered by submission date. Quantities are requested units. No patient information is included.',
  };
};
