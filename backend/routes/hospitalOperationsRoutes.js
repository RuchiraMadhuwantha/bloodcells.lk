const express=require('express');
const auth=require('../middleware/authMiddleware');
const roles=require('../middleware/roleMiddleware');
const {handleValidationErrors:valid}=require('../validators/common');
const v=require('../validators/hospitalValidators');
const c=require('../controllers/hospitalOperationsController');
const router=express.Router();
const transfers=require('../controllers/hospitalTransferController');
router.use(auth,roles('hospital'),c.owner);
router.get('/collection-campaigns',[require('express-validator').query('date').optional().isDate({format:'YYYY-MM-DD',strictMode:true})],valid,async(req,res,next)=>{try{res.json({success:true,available:true,items:await require('../models/campaignDonationModel').choices(req.hospital.hospitalId,req.query.date)});}catch(e){next(e);}});
router.get('/transfer-destinations',transfers.destinations);
router.get('/transfers',transfers.list);
router.get('/transfers/:id',v.id,valid,transfers.details);
router.post('/transfers',v.createTransfer,valid,transfers.send);
router.put('/transfers/:id/receive',v.id,v.receiveTransfer,valid,transfers.receive);
router.get('/inventory',v.range,valid,c.stock);
router.get('/inventory/changes',c.changes);
router.get('/inventory/:id',v.id,valid,c.stockDetails);
router.post('/inventory',v.createStock,valid,c.addStock);
router.put('/inventory/:id',v.updateStock,valid,c.updateStock);
router.get('/blood-usage',v.range,valid,c.usage);
router.get('/blood-usage/:id',v.id,valid,c.usageDetails);
router.post('/blood-usage',v.createUsage,valid,c.addUsage);
router.get('/availability',v.availability,valid,c.availability);
router.get('/dashboard',c.dashboard);
router.get('/reports',v.report,valid,c.report);
router.put('/profile',v.profile,valid,c.updateProfile);
module.exports=router;
